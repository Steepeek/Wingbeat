def fmt_ui(n: float) -> tuple[str, str]:
    """Число для таблицы: (мантисса, суффикс).

    Мантисса и суффикс набираются разными кеглями, поэтому возвращаются
    порознь. Разделитель дробной части — запятая, разряды — узкий неразрывный
    пробел U+202F: в таблице он не рвёт число и не расползается.
    """
    n = float(n)
    if n >= 1_000_000_000:
        return f"{n / 1_000_000_000:.2f}".replace(".", ","), "G"
    if n >= 1_000_000:
        return f"{n / 1_000_000:.2f}".replace(".", ","), "M"
    if n >= 10_000:
        return f"{n / 1000:.1f}".replace(".", ","), "k"
    if n >= 1000:
        return f"{n:,.0f}".replace(",", " "), ""
    return f"{n:.0f}", ""


def fmt_chat(n: float) -> str:
    """Число для вставки в игровой чат.

    Отдельный форматтер намеренно: клиент Aion работает в cp1251, а U+202F
    в неё не входит — символ съело бы или превратило в мусор, и строка
    поехала бы по длине под лимит чата.
    """
    n = float(n)
    if n >= 1_000_000_000:
        return f"{n / 1_000_000_000:.2f}G"
    if n >= 1_000_000:
        return f"{n / 1_000_000:.2f}M"
    if n >= 10_000:
        return f"{n / 1000:.1f}k"
    if n >= 1000:
        return f"{n:,.0f}".replace(",", " ")
    return f"{n:.0f}"


def snap(value: float, dpr: float) -> float:
    """Кладёт координату на границу физического пикселя.

    Волосяная линия без этого размазывается: при масштабе 125 % заливка
    высотой 1 даёт два полупрозрачных ряда вместо одного чёткого.
    """
    return round(value * dpr) / dpr
