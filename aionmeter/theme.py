# --- производные цвета класса --------------------------------------------

_TRIPLE: dict[str, tuple[QColor, QColor, QColor]] = {}
_FALLBACK = "#8FA3B8"


def class_triple(hexrgb: str | None) -> tuple[QColor, QColor, QColor]:
    """(подложка, рельс, нить темпа) из одного цвета класса.

    Светлота подложки фиксирована на 0.13 у ВСЕХ классов: цвет опознаётся
    тоном, а контраст текста не должен зависеть от того, кто в строке.
    Рельс, наоборот, светлый и насыщенный — под ним текста нет.
    """
    key = hexrgb or _FALLBACK
    got = _TRIPLE.get(key)
    if got is not None:
        return got
    base = QColor(key)
    if not base.isValid():
        base = QColor(_FALLBACK)
    h, s, _l, _a = base.getHslF()
    if h < 0:                                  # серый: оттенка нет
        h = 0.0
    wash = QColor.fromHslF(h, min(0.55, s * 0.8), 0.13)
    rail = QColor.fromHslF(h, s, max(base.lightnessF(), 0.60))
    tempo = QColor.fromHslF(h, min(1.0, s * 0.85), 0.78)
    got = (wash, rail, tempo)
    _TRIPLE[key] = got
    return got


